export function naturalHeight(p:Pick<Plant,'name'|'x'|'y'|'height'>){
 const base=NATURAL_HEIGHTS[p.name];if(!base)return p.height;
 const seed=Math.abs(Math.sin(p.x*12.9898+p.y*78.233)*43758.5453)%1;
 return base*(.9+seed*.2);
}
